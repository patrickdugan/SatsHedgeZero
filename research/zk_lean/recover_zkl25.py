"""ZKL-25 recovery: recheck the pinned run-46072770036 receipts against the capture.

Inputs are the downloaded zkl25-graph-results artifact and the decompressed
ZKL-22 capture streams. Nothing is regenerated from untrusted receipt data:
every certificate is re-verified against rows streamed from the pinned
matrix, every bound receipt is rebound (full deletion hash recomputed) and
its Lean source is regenerated byte for byte.
"""
import argparse
import hashlib
import json
from collections import Counter
from pathlib import Path
from types import SimpleNamespace

from audit import digest
from audit_capture import stream_audit
from graph_dependency import ARMS, local_shapes
from local_binding import bind, require_pin
from poly_certificate import verify
from window_dependency import indexed_lean


def failure_modes(tasks):
    out = {}
    for arm in ARMS:
        recs = [(t, t["arms"][arm]) for t in tasks]
        out[arm] = {
            "targets": len(recs),
            "solved": sum(q["exact_identity_checked"] for _, q in recs),
            "solved_by_target_degree": dict(Counter(
                str(t["degree"]) for t, q in recs if q["exact_identity_checked"])),
            "unsolved_by_target_degree": dict(Counter(
                str(t["degree"]) for t, q in recs if not q["exact_identity_checked"])),
            "cap": dict(Counter(str(q["cap"]) for _, q in recs if not q["exact_identity_checked"])),
            "complete_through": dict(Counter(
                str(q["complete_through"]) for _, q in recs if not q["exact_identity_checked"])),
            "empty_neighborhood": sum(not q["retained_global_indices"] for _, q in recs),
            "short_neighborhood": sum(len(q["retained_global_indices"]) < 12 for _, q in recs),
            "multiplier_pool_truncated": sum(q["available_multiplier_wires"] > len(q["multiplier_wires"])
                                             for _, q in recs),
            "cpu_ns": sum(q["cpu_ns"] for _, q in recs),
            "coefficient_work": sum(q["coefficient_work"] for _, q in recs),
        }
    return out


def recover(stream, pin, results):
    campaign = json.loads((results / "campaign.json").read_text())
    require_pin(campaign["original_full_sha256"], pin)
    tasks = campaign["tasks"]
    wanted = set()
    for t in tasks:
        for q in t["arms"].values():
            if q["certificate"] is not None:
                wanted.add(q["target_global_index"])
                wanted.update(q["retained_global_indices"])
    rows = {}
    full = stream_audit(stream, visit=lambda i, row, _p: rows.__setitem__(i, row) if i in wanted else None)
    require_pin(full["canonical_shape_sha256"], pin)
    corpus = SimpleNamespace(rows=rows)
    checked = 0
    for t in tasks:
        for q in t["arms"].values():
            if q["certificate"] is None:
                continue
            a, b = local_shapes(full, corpus, q["target_global_index"], q["retained_global_indices"])
            verify(a, b, q["certificate"], digest(a), digest(b))
            checked += 1
    receipts = []
    for path in sorted(results.glob("*_degree*.json")):
        rec = json.loads(path.read_text())
        source = path.with_suffix(".lean").read_text(encoding="utf-8")
        if hashlib.sha256(source.encode()).hexdigest() != rec["lean_source_sha256"]:
            raise ValueError(f"{path.name}: Lean source hash mismatch")
        bound, a, b = bind(stream, pin, rec["target_global_index"], rec["retained_global_indices"])
        require_pin(bound["deletion_shape_sha256"], rec["replacement_full_sha256"])
        verify(a, b, rec["certificate"], digest(a), digest(b))
        if indexed_lean(a, b, rec["certificate"], rec["target_global_index"],
                        rec["retained_global_indices"]) != source:
            raise ValueError(f"{path.name}: regenerated Lean source differs")
        receipts.append({"file": path.name, "arm": rec["arm"], "degree": rec["degree"],
                         "target_global_index": rec["target_global_index"],
                         "retained_global_indices": rec["retained_global_indices"],
                         "multipliers": len(rec["certificate"]["multipliers"]),
                         "replacement_full_sha256": rec["replacement_full_sha256"],
                         "lean_source_sha256": rec["lean_source_sha256"],
                         "successful_targets": rec["successful_targets"],
                         "rebound": True, "identity_rechecked": True, "source_regenerated": True})
    return {"schema": "zkl25-recovery-v1", "original_full_sha256": pin,
            "constraints": full["constraints"], "wires": full["wires"],
            "search_prefix": campaign["search_prefix"], "targets": campaign["targets"],
            "corpus_counts": campaign["corpus_counts"], "stored_terms": campaign["stored_terms"],
            "local_certificates_rechecked": checked, "bound_receipts": receipts,
            "failure_modes": failure_modes(tasks), "production_accepted": False}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stream", type=Path)
    ap.add_argument("--expected-original", required=True)
    ap.add_argument("--results", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    out = recover(args.stream, args.expected_original, args.results)
    args.out.write_text(json.dumps(out, sort_keys=True, indent=1)+"\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in out.items() if k != "targets"}, sort_keys=True))


if __name__ == "__main__":
    main()
