import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
import {prove,verify,generators,pointBytes,validateGenerators} from '../ipa.mjs';
const dir=dirname(fileURLToPath(import.meta.url));
const epochHash='7a0a6d8d97a231fd0adcef7892d29232d131adfe8c92391deb228b9dd598e51e';
const fx=prove({epochHash,pythPrice:100000n*100000000n,chainlinkPrice:100200n*100000000n});
if(!verify(fx))throw Error('fixture independent verifier failed');
writeFileSync(resolve(dir,'valid.json'),JSON.stringify(fx,null,2)+'\n');
const gs=generators();validateGenerators(gs);
const out=`// GENERATED by fixtures/build_fixture.mjs; pinned deterministic hash-to-curve generators.\n// Security: discrete logs are unknown under the SHA256 try-and-increment derivation.\n// Vector dimension 4. Each point is x||y in little-endian BN254 base field.\npub const G_HEX: [&str;4] = [${gs.g.map(p=>'"'+pointBytes(p).toString('hex')+'"').join(',')}];\npub const H_HEX: [&str;4] = [${gs.h.map(p=>'"'+pointBytes(p).toString('hex')+'"').join(',')}];\npub const U_HEX: &str = "${pointBytes(gs.u).toString('hex')}";\n`;
writeFileSync(resolve(dir,'../near_contract/src/generators.rs'),out);
console.log('Generated transparent IPA fixture and pinned BN254 generators.');
